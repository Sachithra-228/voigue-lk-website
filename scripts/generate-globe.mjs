// Generates src/components/home/globe-data.ts: the land outline, connection arcs and pin positions
// for the Global Connection globe, projected once so no map library ships to visitors.
//
//   node scripts/generate-globe.mjs
//
import fs from "node:fs";
import { createRequire } from "node:module";
import { geoDistance, geoOrthographic, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topology = require("world-atlas/land-110m.json");
const land = feature(topology, topology.objects.land);

const SIZE = 640;
const RADIUS = 290;
const CENTER = [88, 10]; // [longitude, latitude] the globe is turned towards: Sri Lanka in front, Australia and Europe in view

const projection = geoOrthographic()
  .rotate([-CENTER[0], -CENTER[1]])
  .scale(RADIUS)
  .translate([SIZE / 2, SIZE / 2])
  .clipAngle(90)
  .precision(1);
const path = geoPath(projection).digits(0);

const places = {
  colombo: { label: "Colombo", hub: true, at: [79.86, 6.93] },
  melbourne: { label: "Melbourne", hub: true, at: [144.96, -37.81] },
  // Unlabelled pins: they exist to show reach beyond Australia, not to name offices.
  london: { at: [-0.13, 51.51] },
  dubai: { at: [55.27, 25.2] },
  nairobi: { at: [36.82, -1.29] },
  johannesburg: { at: [28.05, -26.2] },
  singapore: { at: [103.82, 1.35] },
  tokyo: { at: [139.69, 35.69] }
};

const connections = [
  ["colombo", "melbourne", true],
  ["colombo", "london"],
  ["colombo", "dubai"],
  ["colombo", "nairobi"],
  ["colombo", "johannesburg"],
  ["colombo", "singapore"],
  ["colombo", "tokyo"],
  ["melbourne", "singapore"],
  ["melbourne", "tokyo"]
];

const facing = (coordinates) => geoDistance(coordinates, CENTER) < Math.PI / 2 - 0.02;

const pins = Object.entries(places)
  .filter(([, place]) => facing(place.at))
  .map(([id, place]) => {
    const [x, y] = projection(place.at);
    return { id, x: Math.round(x * 10) / 10, y: Math.round(y * 10) / 10, ...(place.hub ? { hub: true, label: place.label } : {}) };
  });

const arcs = connections
  .map(([from, to, primary]) => ({
    d: path({ type: "LineString", coordinates: [places[from].at, places[to].at] }),
    primary: Boolean(primary)
  }))
  .filter((arc) => arc.d);

const landPath = path(land);

const output = `// Generated by scripts/generate-globe.mjs. Do not edit by hand.
export const globe = ${JSON.stringify({ size: SIZE, radius: RADIUS, land: landPath, arcs, pins }, null, 2)} as const;
`;

fs.writeFileSync(new URL("../src/components/home/globe-data.ts", import.meta.url), output);
console.log(`land path: ${(landPath.length / 1024).toFixed(1)} KB, arcs: ${arcs.length}, pins: ${pins.length} (${pins.map((p) => p.id).join(", ")})`);
