// Generates src/components/home/globe-data.ts: the land outline, connection arcs and pin positions
// for the Global Connection globe, projected once so no map library ships to visitors.
//
//   node scripts/generate-globe.mjs
//
import fs from "node:fs";
import { createRequire } from "node:module";
import { geoDistance, geoOrthographic, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topology = require("world-atlas/land-110m.json");
const land = feature(topology, topology.objects.land);

const SIZE = 640;
const RADIUS = 290;
const CENTER = [88, 10]; // [longitude, latitude] the globe is turned towards: Sri Lanka in front, Australia and Europe in view

const projection = geoOrthographic()
  .rotate([-CENTER[0], -CENTER[1]])
  .scale(RADIUS)
  .translate([SIZE / 2, SIZE / 2])
  .clipAngle(90)
  .precision(1);
const path = geoPath(projection).digits(0);

const places = {
  colombo: { label: "Colombo", hub: true, at: [79.86, 6.93] },
  melbourne: { label: "Melbourne", hub: true, at: [144.96, -37.81] },
  // Unlabelled pins: they exist to show reach beyond Australia, not to name offices.
  london: { at: [-0.13, 51.51] },
  dubai: { at: [55.27, 25.2] },
  nairobi: { at: [36.82, -1.29] },
  johannesburg: { at: [28.05, -26.2] },
  singapore: { at: [103.82, 1.35] },
  tokyo: { at: [139.69, 35.69] }
};

const connections = [
  ["colombo", "melbourne", true],
  ["colombo", "london"],
  ["colombo", "dubai"],
  ["colombo", "nairobi"],
  ["colombo", "johannesburg"],
  ["colombo", "singapore"],
  ["colombo", "tokyo"],
  ["melbourne", "singapore"],
  ["melbourne", "tokyo"]
];

const facing = (coordinates) => geoDistance(coordinates, CENTER) < Math.PI / 2 - 0.02;

const pins = Object.entries(places)
  .filter(([, place]) => facing(place.at))
  .map(([id, place]) => {
    const [x, y] = projection(place.at);
    return { id, x: Math.round(x * 10) / 10, y: Math.round(y * 10) / 10, ...(place.hub ? { hub: true, label: place.label } : {}) };
  });

const arcs = connections
  .map(([from, to, primary]) => ({
    d: path({ type: "LineString", coordinates: [places[from].at, places[to].at] }),
    primary: Boolean(primary)
  }))
  .filter((arc) => arc.d);

const landPath = path(land);

const output = `// Generated by scripts/generate-globe.mjs. Do not edit by hand.
export const globe = ${JSON.stringify({ size: SIZE, radius: RADIUS, land: landPath, arcs, pins }, null, 2)} as const;
`;

fs.writeFileSync(new URL("../src/components/home/globe-data.ts", import.meta.url), output);

// The same globe as plain SVG markup, for the WordPress theme (template-parts/globe.php).
const centre = SIZE / 2;
const arcMarkup = arcs
  .map((arc) => `<path d="${arc.d}" fill="none" stroke="${arc.primary ? "url(#globe-arc-grad)" : "hsl(256 72% 52% / 0.55)"}" stroke-width="${arc.primary ? 2.6 : 1.5}" stroke-linecap="round" stroke-dasharray="${arc.primary ? "7 9" : "4 7"}" class="${arc.primary ? "globe-arc-primary" : "globe-arc"}"/>`)
  .join("\n\t");
const pinMarkup = pins
  .map((pin) => {
    if (!pin.hub) return `<circle cx="${pin.x}" cy="${pin.y}" r="4.5" fill="hsl(256 72% 52%)" stroke="white" stroke-width="1.5"/>`;
    const left = pin.id === "colombo";
    return `<g><circle cx="${pin.x}" cy="${pin.y}" r="15" fill="hsl(256 72% 52% / 0.18)"/><circle cx="${pin.x}" cy="${pin.y}" r="7" fill="${pin.id === "melbourne" ? "hsl(290 56% 49%)" : "hsl(256 72% 52%)"}" stroke="white" stroke-width="2"/><text x="${pin.x + (left ? -14 : 14)}" y="${pin.y + 5}" text-anchor="${left ? "end" : "start"}" class="globe-label" stroke="white" stroke-width="4" paint-order="stroke">${pin.label}</text></g>`;
  })
  .join("\n\t");
const phpPartial = `<?php
/**
 * Generated by scripts/generate-globe.mjs. Do not edit by hand.
 * World-map globe: Colombo and Melbourne are labelled, the other pins deliberately are not.
 *
 * @package Voigue_Theme
 */

defined( 'ABSPATH' ) || exit;
?>
<svg viewBox="0 0 ${SIZE} ${SIZE}" class="mx-auto h-auto w-full max-w-[560px]" role="img" aria-label="World map globe connecting Sri Lanka and Australia to partners around the world">
	<defs>
		<radialGradient id="globe-sphere" cx="38%" cy="30%" r="78%"><stop offset="0%" stop-color="hsl(262 80% 98%)"/><stop offset="60%" stop-color="hsl(262 62% 92%)"/><stop offset="100%" stop-color="hsl(256 58% 82%)"/></radialGradient>
		<linearGradient id="globe-arc-grad" x1="0" x2="1"><stop offset="0%" stop-color="hsl(256 72% 52%)"/><stop offset="100%" stop-color="hsl(290 56% 49%)"/></linearGradient>
		<clipPath id="globe-clip"><circle cx="${centre}" cy="${centre}" r="${RADIUS}"/></clipPath>
	</defs>
	<circle cx="${centre}" cy="${centre}" r="${RADIUS + 18}" fill="hsl(256 72% 52% / 0.06)"/>
	<circle cx="${centre}" cy="${centre}" r="${RADIUS}" fill="url(#globe-sphere)"/>
	<g clip-path="url(#globe-clip)"><path d="${landPath}" fill="hsl(256 46% 62% / 0.5)" stroke="hsl(256 50% 48% / 0.4)" stroke-width="0.6" stroke-linejoin="round"/></g>
	<circle cx="${centre}" cy="${centre}" r="${RADIUS}" fill="none" stroke="hsl(256 50% 60% / 0.35)" stroke-width="1.2"/>
	${arcMarkup}
	${pinMarkup}
</svg>
`;
fs.writeFileSync(new URL("../wordpress/voigue-theme/template-parts/globe.php", import.meta.url), phpPartial);
console.log(`land path: ${(landPath.length / 1024).toFixed(1)} KB, arcs: ${arcs.length}, pins: ${pins.length} (${pins.map((p) => p.id).join(", ")})`);
